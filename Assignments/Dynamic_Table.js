// ADD EVENT LISTENERS TO TH
const headerCells = headerRow.querySelectorAll("th")
headerCells.forEach((th) => {
    th.addEventListener("click", onHeaderClick);
});

// This is an object to store the state of the sorting.
let sortState = {
    key: null,      // this key shows which column is currently sorted
    direction: "none" // three directions are described "asc" | "desc" | "none"
};


const originalUsers = users.slice();
function onHeaderClick(e) {
    const key = e.currentTarget.dataset.key;


    // Determine next direction
    if (sortState.key !== key) {
        // switching to a new column: start with asc
        sortState.key = key;
        sortState.direction = "asc";
    } else {
        // same column: cycle asc -> desc -> none
        if (sortState.direction === "asc") {
            sortState.direction = "desc";
        } else if (sortState.direction === "desc") {
            sortState.direction = "none";
        } else {
            sortState.direction = "asc";
        }
    }

    applySortAndRender();
}

function getTypeForKey(key) {
    if (["id", "age", "salary"].includes(key)) return "number";
    if (key === "isActive") return "boolean";
    if (key === "joinDate") return "date";
    return "string";
}

function compareValues(a, b, key, direction) {
    const type = getTypeForKey(key);
    let va = a[key];
    let vb = b[key];

    if (type === "number") {
        va = Number(va);
        vb = Number(vb);
    } else if (type === "date") {
        va = new Date(va).getTime();
        vb = new Date(vb).getTime();
    } else if (type === "boolean") {
        // define order: true > false
        va = a[key] ? 1 : 0;
        vb = b[key] ? 1 : 0;
    } else {
        // string
        va = String(va);
        vb = String(vb);
    }

    let cmp = 0;
    if (type === "string") {
        cmp = va.localeCompare(vb);
    } else {
        cmp = va < vb ? -1 : va > vb ? 1 : 0;
    }

    return direction === "asc" ? cmp : -cmp;
}

function applySortAndRender() {
    if (sortState.direction === "none" || !sortState.key) {
        // restore default
        renderRows(originalUsers);
        updateHeaderIndicators();
        return;
    }

    const sorted = originalUsers.slice().sort((a, b) =>
        compareValues(a, b, sortState.key, sortState.direction)
    );
    renderRows(sorted);
    updateHeaderIndicators();
}

function updateHeaderIndicators() {
    // Clear all indicators
    headerCells.forEach((th) => {
        th.textContent = th.dataset.key;
    });

    // Add arrow to current column
    if (sortState.key && sortState.direction !== "none") {
        const th = Array.from(headerCells).find(h => h.dataset.key === sortState.key);
        if (th) {
            const arrow = sortState.direction === "asc" ? " ↑" : " ↓";
            th.textContent = th.dataset.key + arrow;
        }
    }
}

